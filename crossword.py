"""Daily mini crossword, in the style of the New York Times Mini.

Deliberately NOT generated by the language model, for the same reason the
Sudoku isn't. A crossword is only solvable if every crossing letter agrees, and
"please make sure the intersections line up" is not a guarantee - it's a hope.
One bad crossing produces a puzzle that cannot be finished, and a nine-year-old
does not experience that as a broken grid. She experiences it as being stupid.

So the grid is filled here, by backtracking over a vetted word list, and every
across and down entry is checked against that list before the puzzle can ship.
Correctness is true by construction.

    age 9  -> 5x5
    age 11 -> 7x7

Everything is seeded from the date, so both kids get the same puzzle all day
and it changes overnight. No API cost, no failure mode, no network.
"""

