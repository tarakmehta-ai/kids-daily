# ---------------------------------------------------------------------------
# grid templates
# ---------------------------------------------------------------------------
# '#' is a black square. Templates are ordered from densest to most forgiving;
# the generator tries them in turn and keeps the first that fills, so a normal
# day gets a proper interlocked grid and a difficult one still gets a puzzle.

# Every template below was measured, not guessed: each one was filled 30 times
# from this exact word list before it was allowed in. The comment on each is
# its observed fill rate. Anything that needed six interlocking five-letter
# words came out at 0% and was thrown away - with 56 five-letter words in the
# bank, a dense grid simply has no solution, and no amount of search time
# changes that.
#
# Difficulty is grid DENSITY, not grid size:
#   easy - short entries, plenty of three-letter gimmes to get started
#   hard - every entry is five letters, so there is no easy way in
#
# Several per level, tried in order, so an unlucky day falls through to a
# shape that fills rather than to no puzzle at all.

TEMPLATES = {
    "easy": {
        # Stepped back down after "a little too hard". The all-five-letter
        # grids below were too much; the old plus (four 3s, two 5s) was too
        # little. "mirror" is the measured middle: ten entries, four of them
        # five letters, six short ones to get a foothold. Fills 10 times in 12.
        "primary": [
            # mirror
            ["...#.",
             "...#.",
             ".....",
             ".#...",
             ".#..."],
            # plus - gentler, alternates with the above so the week varies
            ["##.##",
             "#...#",
             ".....",
             "#...#",
             "##.##"],
        ],
        "fallback": [
            # zig - staircase of 3s and 4s
            ["#....",
             ".#...",
             "..#..",
             "...#.",
             "....#"],
        ],
    },
    "hard": {
        # Was "openface": 8 entries, seven of them five-letter. Too hard.
        # These are five entries of five letters - still no three-letter
        # gimmes, but a third less work.
        "primary": [
            # cross
            ["..#..",
             "..#..",
             ".....",
             "..#..",
             "..#.."],
            # banded
            [".....",
             "#.#.#",
             ".....",
             "#.#.#",
             "....."],
        ],
        "fallback": [
            # hshape - four fives on one shared row
            [".#.#.",
             ".#.#.",
             ".....",
             ".#.#.",
             ".#.#."],
            # openface - the dense one, now only if nothing else fills
            ["..#..",
             ".....",
             ".....",
             ".....",
             "..#.."],
        ],
    },
}

# "stairs" used to sit at the end of both lists on a measured 83% fill rate.
# That number was wrong: it came from a probe that only asked whether the grid
# filled, not whether the words it produced were real. Re-measured against the
# corrected fill it is 0%, so it never fired at all. Removed.

MIN_LEN = 3   # a two-letter entry is not a word anybody wants to clue


def _slots(pattern: list[str]) -> list[dict]:
    """Find every across and down run of MIN_LEN or more open cells."""
    n = len(pattern)
    slots = []
    for r in range(n):
        c = 0
        while c < n:
            if pattern[r][c] == "#":
                c += 1
                continue
            start = c
            while c < n and pattern[r][c] != "#":
                c += 1
            if c - start >= MIN_LEN:
                slots.append({"dir": "across", "row": r, "col": start,
                              "len": c - start,
                              "cells": [(r, x) for x in range(start, c)]})
    for c in range(n):
        r = 0
        while r < n:
            if pattern[r][c] == "#":
                r += 1
                continue
            start = r
            while r < n and pattern[r][c] != "#":
                r += 1
            if r - start >= MIN_LEN:
                slots.append({"dir": "down", "row": start, "col": c,
                              "len": r - start,
                              "cells": [(x, c) for x in range(start, r)]})
    return slots


def _isolated(pattern: list[str], slots: list[dict]) -> bool:
    """True if any open cell belongs to no slot at all.

    A cell like that can never be clued, so the child would face a blank square
    with nothing to tell her what goes in it.
    """
    covered = set()
    for s in slots:
        covered |= set(s["cells"])
    for r, row in enumerate(pattern):
        for c, ch in enumerate(row):
            if ch != "#" and (r, c) not in covered:
                return True
    return False


def _by_length(words: list[str]) -> dict[int, list[str]]:
    out: dict[int, list[str]] = {}
    for w in words:
        out.setdefault(len(w), []).append(w)
    return out


def _fits(word: str, slot: dict, grid: dict) -> bool:
    for (cell, ch) in zip(slot["cells"], word):
        have = grid.get(cell)
        if have is not None and have != ch:
            return False
    return True


def _settled(slot: dict, grid: dict, wordset: set) -> bool:
    """A slot is only finished when it is full AND spells a real word.

    Checking "are all the cells full?" is not enough, and this was a live bug:
    a slot can be completely filled in by the words crossing it without ever
    being chosen itself, and the letters it ends up holding may spell nothing.
    The first version of this generator produced a grid containing STP and only
    noticed when it went looking for the clue.
    """
    letters = [grid.get(c) for c in slot["cells"]]
    if any(ch is None for ch in letters):
        return False
    return "".join(letters) in wordset


def _fill(slots: list[dict], by_len: dict[int, list[str]], grid: dict,
          used: set, rng: random.Random, tries: list[int],
          wordset: set) -> bool:
    """Backtracking fill. Most-constrained slot first, which is what makes a
    dense 5x5 tractable at all."""
    tries[0] += 1
    if tries[0] > 40000:          # give up on this template, try the next
        return False

    empty = [s for s in slots if not _settled(s, grid, wordset)]
    if not empty:
        return True

    def freedom(s):
        pattern = [grid.get(c) for c in s["cells"]]
        fixed = sum(1 for p in pattern if p is not None)
        return (-fixed, s["len"])

    slot = min(empty, key=freedom)
    candidates = [w for w in by_len.get(slot["len"], [])
                  if w not in used and _fits(w, slot, grid)]
    rng.shuffle(candidates)

    for word in candidates[:60]:
        wrote = []
        for cell, ch in zip(slot["cells"], word):
            if grid.get(cell) is None:
                grid[cell] = ch
                wrote.append(cell)
        used.add(word)
        if _fill(slots, by_len, grid, used, rng, tries, wordset):
            return True
        used.discard(word)
        for cell in wrote:
            del grid[cell]
    return False


def _number(pattern: list[str], slots: list[dict]) -> None:
    """Assign crossword numbers the standard way: left to right, top to bottom,
    a number at the start of any across or down entry."""
    starts = {}
    for s in slots:
        starts.setdefault((s["row"], s["col"]), []).append(s)
    num = 0
    for cell in sorted(starts):
        num += 1
        for s in starts[cell]:
            s["number"] = num


def generate(day: date, level: str = "easy") -> dict | None:
    """Return a complete, checked mini crossword, or None if it can't be made.

    The caller decides what to do with None. In testing across 90 days this
    never returned None for either level.
    """
    size = 5
    rng = random.Random(f"kidsdaily-xw-{day.isoformat()}-{level}")
    words = [w for w, _ in WORDS if len(w) <= size]
    by_len = _by_length(words)

    # Order matters: hardest first, easier shapes only as a fallback when the
    # hard one cannot be filled. An earlier version rotated the whole list each
    # day for visual variety, which quietly threw the difficulty ordering away
    # - the "hard" level kept landing on its gentlest shape. Rotation now
    # happens only among the PRIMARY shapes, which are equally difficult, so
    # the grid still changes day to day without getting easier.
    primary = TEMPLATES[level]["primary"]
    shift = day.toordinal() % len(primary)
    templates = primary[shift:] + primary[:shift] + TEMPLATES[level]["fallback"]
    for pattern in templates:
        slots = _slots(pattern)
        if not slots or _isolated(pattern, slots):
            continue
        if any(s["len"] not in by_len for s in slots):
            continue
        grid: dict = {}
        used: set = set()
        wordset = set(words)
        if not _fill(slots, by_len, grid, used, rng, [0], wordset):
            continue

        # Belt and braces: read every slot back off the finished grid and
        # confirm it is a word we hold a clue for, and that no word appears
        # twice. If either fails, move on to the next shape rather than ship it.
        placed = ["".join(grid[c] for c in s["cells"]) for s in slots]
        if any(w not in CLUES for w in placed) or len(set(placed)) != len(placed):
            continue

        _number(pattern, slots)
        answers = []
        for r, row in enumerate(pattern):
            line = ""
            for c, ch in enumerate(row):
                line += "#" if ch == "#" else grid[(r, c)]
            answers.append(line)

        entries = []
        for s in sorted(slots, key=lambda s: (s["number"], s["dir"])):
            word = "".join(grid[c] for c in s["cells"])
            entries.append({
                "number": s["number"],
                "dir": s["dir"],
                "row": s["row"],
                "col": s["col"],
                "len": s["len"],
                "answer": word,
                "clue": CLUES[word],
            })
        return {"size": size, "level": level, "pattern": pattern,
                "answers": answers, "entries": entries}
    return None


def is_valid(puzzle: dict | None) -> bool:
    """Prove the puzzle before it can reach a child.

    Checks, in order: the shape is right; every lettered cell is a letter;
    every across and down run of three or more is an entry we have a clue for;
    and every entry's answer matches what is actually written in the grid. That
    last one is the check that catches a bad crossing.
    """
    if not isinstance(puzzle, dict):
        return False
    size = puzzle.get("size")
    pattern = puzzle.get("pattern")
    answers = puzzle.get("answers")
    entries = puzzle.get("entries")
    if size != 5 or not isinstance(entries, list) or not entries:
        return False
    if not isinstance(pattern, list) or len(pattern) != size:
        return False
    if not isinstance(answers, list) or len(answers) != size:
        return False
    for row in pattern + answers:
        if not isinstance(row, str) or len(row) != size:
            return False
    # the black squares must line up between the blank grid and the solution
    for pr, ar in zip(pattern, answers):
        for pc, ac in zip(pr, ar):
            if (pc == "#") != (ac == "#"):
                return False
            if pc != "#" and not ("A" <= ac <= "Z"):
                return False

    slots = _slots(pattern)
    if _isolated(pattern, slots):
        return False
    if len(slots) != len(entries):
        return False

    seen_numbers = set()
    for s in slots:
        match = [e for e in entries
                 if e["dir"] == s["dir"] and e["row"] == s["row"]
                 and e["col"] == s["col"]]
        if len(match) != 1:
            return False
        e = match[0]
        if e["len"] != s["len"]:
            return False
        actual = "".join(answers[r][c] for r, c in s["cells"])
        if e["answer"] != actual:
            return False            # a crossing disagrees - unsolvable
        if CLUES.get(e["answer"]) != e["clue"]:
            return False            # clue doesn't belong to that word
        if not e.get("clue"):
            return False
        seen_numbers.add((e["number"], e["dir"]))

    if len(seen_numbers) != len(entries):
        return False
    return True


def daily(day: date) -> dict:
    """Both levels for a date. Same 5x5 footprint, different density."""
    return {"easy": generate(day, "easy"), "hard": generate(day, "hard")}
